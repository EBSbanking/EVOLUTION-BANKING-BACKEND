// Update a threshold rule
export const updateThreshold = async (req, res) => {
  try {
    const { transaction_type } = req.params;
    const updates = req.body;
    const USER_ID = req.body.USER_ID || req.user_id || 'system';  // From body or middleware
    const ipAddress = req.ip || req.headers['x-forwarded-for'] || req.connection.remoteAddress;

    // Optional: Validate required fields
    if (!transaction_type) {
      return res.status(400).json({ message: 'transaction_type is required in URL' });
    }

    if (!updates || typeof updates !== 'object') {
      return res.status(400).json({ message: 'Update payload is required' });
    }

    // Fetch existing for old_value
    const existing = await AMLThreshold.findOne({ transaction_type });
    if (!existing) {
      return res.status(404).json({ message: `No threshold rule found for transaction_type: ${transaction_type}` });
    }

    const oldValue = JSON.stringify(existing);

    // Perform update
    const rule = await AMLThreshold.findOneAndUpdate(
      { transaction_type },
      {
        $set: {
          ...updates,
          updated_at: new Date()
        }
      },
      { new: true }
    );

    // Audit via hybrid logger
    auditLogger.info('Audit Event', {
      entity_type: 'THRESHOLD_RULE',
      entity_id: rule._id,
      user_id: USER_ID,
      action: 'UPDATE',
      old_value: oldValue,
      new_value: JSON.stringify(rule),
      ip_address: ipAddress,
      event_type: 'THRESHOLD_UPDATE',
      outcome: 'success'
    });

    return res.status(200).json({
      message: 'Threshold successfully updated',
      data: rule
    });
  } catch (error) {
    console.error('Update Threshold Error:', error);
    // Audit failure (non-blocking)
    auditLogger.error('Audit Event', {
      entity_type: 'THRESHOLD_RULE',
      entity_id: req.params.transaction_type || null,
      user_id: req.body.USER_ID || 'system',
      action: 'update_threshold',
      old_value: null,
      new_value: null,
      ip_address: req.ip || 'unknown',
      event_type: 'THRESHOLD_ERROR',
      outcome: 'failure',
      error: error.message
    });
    return res.status(500).json({
      message: 'An error occurred while updating the threshold',
      error: error.message
    });
  }
};

