import AMLThreshold from '../models/AMLThreshold.js';
import auditLogger from '../utils/AuditLogger.js';  // Fixed: Default import for hybrid logger
import { GENERAL_TX_TYPES } from '../constants/transactionTypes.js';
import { generateTransactionIds } from '../utils/generateAccountNumber.js';

export const createThreshold = async (req, res) => {
  try {
    const { transaction_type, threshold_amount, currency, active, USER_ID } = req.body;

    // Validate transaction type
    if (!GENERAL_TX_TYPES.includes(transaction_type)) {
      return res.status(400).json({ message: 'Invalid transaction type.' });
    }

    // Check if threshold already exists
    const existing = await AMLThreshold.findOne({ transaction_type });
    if (existing) {
      return res.status(400).json({ message: 'Threshold rule already exists for this transaction type.' });
    }

    // Create new threshold rule
    const rule = new AMLThreshold({
      transaction_type,
      threshold_amount,
      currency,
      active,
      threshold_id: generateTransactionIds('THRESHOLD')
    });

    await rule.save();

    const ipAddress = req.ip || req.headers['x-forwarded-for'] || req.connection.remoteAddress;

    // Audit via hybrid logger (event_id auto-generated by pre-save hook)
    auditLogger.info('Audit Event', {
      entity_type: 'THRESHOLD_RULE',
      entity_id: rule._id,
      user_id: USER_ID,
      action: 'CREATE',
      old_value: null,
      new_value: rule.toObject(),  // Includes auto-generated event_id
      ip_address: ipAddress,
      event_type: 'THRESHOLD_CREATE',
      outcome: 'success'
    });

    return res.status(201).json({
      message: 'Threshold rule created successfully',
      data: rule
    });

  } catch (err) {
    console.error('Error in createThreshold:', err);
    // Audit failure (non-blocking)
    auditLogger.error('Audit Event', {
      entity_type: 'THRESHOLD_RULE',
      entity_id: null,
      user_id: req.body.USER_ID || 'system',
      action: 'create_threshold',
      old_value: null,
      new_value: null,
      ip_address: req.ip || 'unknown',
      event_type: 'THRESHOLD_ERROR',
      outcome: 'failure',
      error: err.message
    });
    return res.status(500).json({
      message: 'Failed to create threshold rule',
      error: process.env.NODE_ENV === 'development' ? err.message : undefined
    });
  }
};

